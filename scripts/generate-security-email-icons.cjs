// Build-time only: rasterize the existing Lucide icon set into tiny CID-safe PNGs.
// Sharp is already bundled with Next.js; no runtime image library is needed by email rendering.
const fs = require("node:fs"), path = require("node:path");
const React = require("react"), { renderToStaticMarkup } = require("react-dom/server");
const icons = require("lucide-react"), sharp = require("sharp");
const definitions = {
  shieldCheck: ["ShieldCheck", 48, "#32637b"],
  shieldAlert: ["ShieldAlert", 48, "#9b4e1a"],
  userShield: ["ShieldUser", 48, "#32637b"],
  lock: ["LockKeyhole", 48, "#32637b"],
  mail: ["MailCheck", 48, "#32637b"],
  key: ["KeyRound", 48, "#32637b"],
  desktop: ["Monitor", 20, "#527186"],
  mobile: ["Smartphone", 20, "#527186"],
  user: ["UserRound", 20, "#527186"],
  location: ["MapPin", 20, "#527186"],
  network: ["Globe2", 20, "#527186"],
  clock: ["Clock3", 20, "#527186"],
};
async function main() {
  const data = {};
  for (const [name, [component, size, color]] of Object.entries(definitions)) {
    const svg = name === "userShield"
      ? `<svg xmlns="http://www.w3.org/2000/svg" width="${size * 2}" height="${size * 2}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"><circle cx="9" cy="7" r="3"/><path d="M3 20v-2a6 6 0 0 1 8-5.65"/><path d="m17 11 5 2v3c0 3-2.5 5-5 6-2.5-1-5-3-5-6v-3l5-2Z"/><path d="m15 16 1.4 1.4L19 15"/></svg>`
      : renderToStaticMarkup(React.createElement(icons[component], { size: size * 2, color, strokeWidth: 1.6 }));
    data[name] = (await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true }).toBuffer()).toString("base64");
  }
  const source = `// Generated by scripts/generate-security-email-icons.cjs from the existing Lucide set.\n// Tiny embedded PNGs: no external image request, icon font, SVG email support or runtime rasterizer.\nexport const SECURITY_EMAIL_ICONS = ${JSON.stringify(data, null, 2)} as const;\nexport type SecurityEmailIconName = keyof typeof SECURITY_EMAIL_ICONS;\n`;
  fs.writeFileSync(path.resolve(__dirname, "../lib/security-email-icons.ts"), source);
  console.log(`Generated ${Object.keys(data).length} embedded icons (${Object.values(data).reduce((sum, value) => sum + Buffer.from(value, "base64").length, 0)} PNG bytes total).`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
